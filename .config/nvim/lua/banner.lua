-- ── Render ───────────────────────────────────────────────────
local function pad(glyph)
  local width = 0
  for _, row in ipairs(glyph) do
    width = math.max(width, vim.fn.strdisplaywidth(row))
  end
  local out = {}
  for i, row in ipairs(glyph) do
    out[i] = row .. string.rep(" ", width - vim.fn.strdisplaywidth(row))
  end
  return out
end

function M.render(text)
  local glyphs = {}
  for ch in text:lower():gmatch(".") do
    if font[ch] then glyphs[#glyphs + 1] = pad(font[ch]) end
  end
  if #glyphs == 0 then return nil end

  local lines = {}
  for row = 1, 6 do
    local parts = {}
    for _, g in ipairs(glyphs) do parts[#parts + 1] = g[row] end
    lines[row] = table.concat(parts)
  end

  if vim.fn.strdisplaywidth(lines[1]) > vim.o.columns - 4 then return nil end
  return lines
end

return M
